@app.route("/activate-plan", methods=["POST"])
@login_required
def activate_plan():
    if not valid_csrf():
        flash("Your form expired. Refresh the page and try again.", "error")
        return redirect(url_for("plans_page"))

    plan_name = request.form.get("plan", "").strip()
    plan = find_plan(plan_name)

    if not plan:
        flash("Please select a valid plan.", "error")
        return redirect(url_for("plans_page"))

    db = get_db()
    try:
        db.execute("BEGIN")
        user = db.execute(
            "SELECT id, plan, balance, referred_by FROM users WHERE id = %s FOR UPDATE",
            (session["user_id"],)
        ).fetchone()

        if user is None:
            db.rollback()
            session.clear()
            return redirect(url_for("login"))

        if user["plan"] == plan_name:
            db.rollback()
            flash("You already have this plan activated.", "error")
            return redirect(url_for("plans_page"))

        fee = int(plan["fee"] if isinstance(plan, dict) else plan.fee)

        if float(user["balance"] or 0) < fee:
            db.rollback()
            flash(
                f"Insufficient balance. You need ₦{fee:,.0f} to activate {plan_name}.",
                "error"
            )
            return redirect(url_for("plans_page"))

        db.execute(
            "UPDATE users SET balance = balance - %s, plan = %s "
            "WHERE id = %s AND balance >= %s",
            (fee, plan_name, user["id"], fee)
        )

        updated = db.execute(
            "SELECT balance, plan FROM users WHERE id = %s",
            (user["id"],)
        ).fetchone()

        if updated is None or updated["plan"] != plan_name:
            db.rollback()
            flash("Activation could not be completed. Please try again.", "error")
            return redirect(url_for("plans_page"))

        # Pay a referral commission only on the member's first paid
        # activation. The unique ledger entry prevents duplicate payouts.
        if user["plan"] == "None" and user["referred_by"] is not None:
            commission = (fee * 40) // 100
            already_paid = db.execute(
                "SELECT id FROM referral_commissions WHERE referred_user_id = %s",
                (user["id"],)
            ).fetchone()

            if already_paid is None:
                db.execute(
                    """
                    INSERT INTO referral_commissions
                        (referred_user_id, referrer_id, plan_name,
                         activation_fee, commission_amount)
                    VALUES (%s, %s, %s, %s, %s)
                    """,
                    (
                        user["id"],
                        user["referred_by"],
                        plan_name,
                        fee,
                        commission
                    )
                )
                db.execute(
                    "UPDATE users SET balance = balance + %s WHERE id = %s",
                    (commission, user["referred_by"])
                )

        db.commit()
        flash(
            f"{plan_name} plan activated successfully. ₦{fee:,.0f} deducted.",
            "success"
        )
        return redirect(url_for("dashboard"))

    except Exception:
        db.rollback()
        app.logger.exception("Plan activation failed")
        flash("Activation failed. Your balance was not charged.", "error")
        return redirect(url_for("plans_page"))

