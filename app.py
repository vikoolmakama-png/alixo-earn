    if not valid_csrf():
        flash("Invalid form token.", "error")
        return redirect(url_for("admin_dashboard"))

    decision = request.form.get("decision", "").title()
    if decision not in ("Approved", "Rejected"):
        flash("Invalid decision.", "error")
        return redirect(url_for("admin_dashboard"))

    db = get_db()
