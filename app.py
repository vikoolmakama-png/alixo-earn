def init_db():
    """Create PostgreSQL tables only; never reads or migrates alixo.db."""
    schema = """
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        phone TEXT NOT NULL UNIQUE,
        username TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        referral_code TEXT NOT NULL UNIQUE,
        referred_by BIGINT REFERENCES users(id),
        plan TEXT NOT NULL DEFAULT 'None',
        balance BIGINT NOT NULL DEFAULT 0,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique
        ON users (LOWER(username));
    CREATE TABLE IF NOT EXISTS referral_commissions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        referred_user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
        referrer_id BIGINT NOT NULL REFERENCES users(id),
        plan_name TEXT NOT NULL,
        activation_fee BIGINT NOT NULL CHECK (activation_fee > 0),
        commission_amount BIGINT NOT NULL CHECK (commission_amount >= 0),
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS deposits (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id),
        amount BIGINT NOT NULL CHECK (amount > 0),
        sender_name TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'Pending',
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        reviewed_at TIMESTAMP,
        reviewed_by TEXT
    );
    CREATE TABLE IF NOT EXISTS withdrawals (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id),
        amount BIGINT NOT NULL CHECK (amount > 0),
        account_name TEXT NOT NULL DEFAULT '',
        account_number TEXT NOT NULL DEFAULT '',
        bank_name TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'Pending',
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        reviewed_at TIMESTAMP,
        reviewed_by TEXT
    );
    CREATE TABLE IF NOT EXISTS tasks (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        instructions TEXT NOT NULL DEFAULT '',
        reward DOUBLE PRECISION NOT NULL DEFAULT 0,
        plan TEXT NOT NULL DEFAULT 'All',
        status TEXT NOT NULL DEFAULT 'Active',
        task_link TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    ALTER TABLE tasks ADD COLUMN IF NOT EXISTS task_link TEXT NOT NULL DEFAULT '';
    CREATE TABLE IF NOT EXISTS task_submissions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id),
        task_id BIGINT NOT NULL REFERENCES tasks(id),
        submitted_username TEXT NOT NULL,
        reward DOUBLE PRECISION NOT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(user_id, task_id)
    );
    """
    with psycopg.connect(get_database_url()) as db:
        db.execute(schema)


def csrf_token():
    if "_csrf_token" not in session:
        session["_csrf_token"] = secrets.token_urlsafe(32)
    return session["_csrf_token"]


app.jinja_env.globals["csrf_token"] = csrf_token


def valid_csrf():
    token = request.form.get("csrf_token", "")
    saved = session.get("_csrf_token") or session.get("csrf_token", "")
    return bool(token and saved and hmac.compare_digest(token, saved))



def login_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if "user_id" not in session:
            flash("Please log in to access your dashboard.", "info")
            return redirect(url_for("login"))
        return view(*args, **kwargs)
    return wrapped


