@app.route("/tasks")
@login_required
def tasks_page():
    db = get_db()
    user = db.execute(
        "SELECT * FROM users WHERE id = %s",
        (session["user_id"],)
    ).fetchone()

    if user is None:
        session.clear()
        return redirect(url_for("login"))

    active_plan = find_plan(user["plan"])
    published_tasks = []

    if active_plan:
        rows = db.execute(
            """SELECT * FROM tasks
               WHERE status = 'Active'
               AND (plan = 'All' OR plan = %s)
               AND id NOT IN (
                   SELECT task_id FROM task_submissions
                   WHERE user_id = %s
               )
               ORDER BY id DESC""",
            (user["plan"], user["id"])
        ).fetchall()

        for row in rows:
            task = dict(row)
            # An "All plans" task pays according to the member's
            # currently activated plan, not a single shared amount.
            if task["plan"] == "All":
                task["display_reward"] = int(active_plan["daily"])
            else:
                task["display_reward"] = int(
                    next(p["daily"] for p in PLANS
                         if p["name"] == task["plan"])
                )
            published_tasks.append(task)

    return render_template(
        "tasks.html",
        user=user,
        active_plan=active_plan,
        published_tasks=published_tasks
    )




@app.route("/tasks/<int:task_id>/submit", methods=["POST"])
@login_required
def submit_task(task_id):
    if not valid_csrf():
        flash("Invalid form token. Please try again.", "error")
        return redirect(url_for("tasks_page"))

    submitted_username = request.form.get("submitted_username", "").strip()
    if not submitted_username or len(submitted_username) > 100:
        flash("Enter your task username.", "error")
        return redirect(url_for("tasks_page"))

    db = get_db()
    try:
        db.execute("BEGIN")
        user = db.execute(
            "SELECT id, plan FROM users WHERE id=%s FOR UPDATE",
            (session["user_id"],)
        ).fetchone()

        if user is None:
            db.rollback()
            session.clear()
            return redirect(url_for("login"))

        plan = find_plan(user["plan"])
        if not plan:
            db.rollback()
            flash("Activate a membership plan first.", "error")
            return redirect(url_for("tasks_page"))

        task = db.execute(
            "SELECT id, plan, status FROM tasks WHERE id=%s",
            (task_id,)
        ).fetchone()

        if not task or task["status"] != "Active":
            db.rollback()
            flash("This task is unavailable.", "error")
            return redirect(url_for("tasks_page"))

        if task["plan"] not in ("All", user["plan"]):
            db.rollback()
            flash("This task is not available for your plan.", "error")
            return redirect(url_for("tasks_page"))

        if task["plan"] == "All":
            reward = int(plan["daily"])
        else:
            chosen = next(
                (x for x in PLANS if x["name"] == task["plan"]), None
            )
            if chosen is None:
                db.rollback()
                flash("Could not determine the reward.", "error")
                return redirect(url_for("tasks_page"))
            reward = int(chosen["daily"])

        db.execute("""
            INSERT INTO task_submissions
                (user_id, task_id, submitted_username, reward)
            VALUES (%s, %s, %s, %s)
        """, (user["id"], task_id, submitted_username, reward))

        db.execute(
            "UPDATE users SET balance=COALESCE(balance, 0)+%s WHERE id=%s",
            (reward, user["id"])
        )
        db.commit()
        flash(f"Success! ₦{reward:,.0f} added to your balance.", "success")

    except psycopg.IntegrityError:
        db.rollback()
        flash("You have already claimed this task.", "error")
    except Exception:
        db.rollback()
        app.logger.exception("Task submission failed")
        flash("Submission failed; no reward was credited.", "error")

    return redirect(url_for("tasks_page"))


@app.route("/withdraw", methods=["GET", "POST"])
@login_required
def withdraw():
    db = get_db()
    user = db.execute(
        "SELECT * FROM users WHERE id = %s",
        (session["user_id"],)
    ).fetchone()

    if user is None:
        session.clear()
        return redirect(url_for("login"))

    active_plan = find_plan(user["plan"])

    if request.method == "POST":
        if not valid_csrf():
            flash("Your form expired. Please try again.", "error")
            return redirect(url_for("withdraw"))

        if active_plan is None:
            flash("Activate an eligible plan before requesting a withdrawal.", "error")
            return redirect(url_for("withdraw"))

        account_name = request.form.get("account_name", "").strip()
        account_number = request.form.get("account_number", "").strip()
        bank_name = request.form.get("bank_name", "").strip()
        amount_text = request.form.get("amount", "").strip()

        if not account_name or not bank_name:
            flash("Enter the account name and bank name.", "error")
            return redirect(url_for("withdraw"))

        if not re.fullmatch(r"[0-9]{10}", account_number):
            flash("Enter a valid 10-digit bank account number.", "error")
            return redirect(url_for("withdraw"))

        if not amount_text.isdigit():
            flash("Enter a valid whole-number withdrawal amount.", "error")
            return redirect(url_for("withdraw"))

        amount = int(amount_text)
        minimum = active_plan["withdrawal"]

        if amount < minimum:
            flash(f"Your plan's minimum withdrawal is ₦{minimum:,.0f}.", "error")
            return redirect(url_for("withdraw"))

        if amount > user["balance"]:
            flash("Your requested amount exceeds your recorded balance.", "error")
            return redirect(url_for("withdraw"))

        flash(
            "Your details passed basic checks, but withdrawal requests "
            "are not yet enabled. No money has been deducted or sent.",
            "info"
        )
        return redirect(url_for("withdraw"))

    referral_total = db.execute(
        "SELECT COALESCE(SUM(commission_amount), 0) "
        "FROM referral_commissions WHERE referrer_id = %s",
        (user["id"],)
    ).fetchone()[0]

    return render_template(
        "withdraw.html",
        user=user,
        active_plan=active_plan,
        referral_total=referral_total,
        main_available=user["balance"],
        referral_available=0
    )

