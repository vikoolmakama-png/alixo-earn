def admin_login():
    if request.method == "POST":
        if not valid_csrf():
            flash("Invalid form token.", "error")
            return redirect(url_for("admin_login"))

        username = os.environ.get("ALIXO_ADMIN_USERNAME", "admin")
        password_hash = os.environ.get("ALIXO_ADMIN_PASSWORD_HASH", "")

        if (
            password_hash
            and hmac.compare_digest(
                request.form.get("username", ""), username
            )
            and check_password_hash(
                password_hash, request.form.get("password", "")
            )
        ):
            session.clear()
            session["is_admin"] = True
            session["_csrf_token"] = secrets.token_urlsafe(32)
            return redirect(url_for("admin_dashboard"))

        flash("Incorrect admin username or password.", "error")

    return render_template("admin_login.html")


