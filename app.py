@app.route("/admin/review-deposit/<int:deposit_id>", methods=["POST"])
@admin_required
def admin_review_deposit(deposit_id):
    if not valid_csrf():
        flash("Invalid form token.", "error")
        return redirect(url_for("admin_dashboard"))

    decision = request.form.get("decision", "").title()
    if decision not in ("Approved", "Rejected"):
        flash("Invalid decision.", "error")
        return redirect(url_for("admin_dashboard"))

    db = get_db()
    try:
        db.execute("BEGIN")
        row = db.execute(
            "SELECT * FROM deposits WHERE id=%s FOR UPDATE", (deposit_id,)
        ).fetchone()

        if not row or row["status"] != "Pending":
            db.rollback()
            flash("Deposit already reviewed or not found.", "error")
            return redirect(url_for("admin_dashboard"))

        db.execute(
            """UPDATE deposits SET status=%s, reviewed_at=CURRENT_TIMESTAMP,
               reviewed_by='admin' WHERE id=%s AND status='Pending'""",
            (decision, deposit_id)
        )

        if decision == "Approved":
            db.execute(
                "UPDATE users SET balance=balance+%s WHERE id=%s",
                (row["amount"], row["user_id"])
            )

        db.commit()
        flash("Deposit " + decision.lower() + ".", "success")
    except Exception:
        db.rollback()
        raise

    return redirect(url_for("admin_dashboard"))


