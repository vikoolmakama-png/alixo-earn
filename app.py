@app.route("/register", methods=["GET", "POST"])
def register():
    if request.method == "POST":
        if not valid_csrf():
            flash("Your form expired. Please try again.", "error")
            return redirect(url_for("register"))

        phone = request.form.get("phone", "").strip()
        username = request.form.get("username", "").strip()
        referral = request.form.get("referral_code", "").strip().upper()
        password = request.form.get("password", "")
        confirm = request.form.get("confirm_password", "")

        if not re.fullmatch(r"[A-Za-z0-9_]{3,24}", username):
            flash(
                "Username must be 3–24 characters using letters, "
                "numbers or underscores.", "error"
            )
            return redirect(url_for("register"))

        if not re.fullmatch(r"\+?[0-9]{7,15}", phone):
            flash("Enter a valid phone number.", "error")
            return redirect(url_for("register"))

        if len(password) < 8:
            flash("Your password must contain at least 8 characters.", "error")
            return redirect(url_for("register"))

        if len(password) > 128:
            flash("Your password is too long.", "error")
            return redirect(url_for("register"))

        if password != confirm:
            flash("Your passwords do not match.", "error")
            return redirect(url_for("register"))

        db = get_db()

        if db.execute(
            "SELECT id FROM users WHERE LOWER(username) = LOWER(%s)",
            (username,)
        ).fetchone():
            flash("That username is already taken.", "error")
            return redirect(url_for("register"))

        if db.execute(
            "SELECT id FROM users WHERE phone = %s", (phone,)
        ).fetchone():
            flash("That phone number is already registered.", "error")
            return redirect(url_for("register"))

        referred_by = None

        if referral:
            referrer = db.execute(
                "SELECT id FROM users WHERE referral_code = %s",
                (referral,)
            ).fetchone()

            if not referrer:
                flash("That referral code is invalid.", "error")
                return redirect(url_for("register"))

            referred_by = referrer["id"]

        own_code = "ALX" + secrets.token_hex(5).upper()

        try:
            cursor = db.execute("""
                INSERT INTO users (
                    phone, username, password_hash,
                    referral_code, referred_by
                )
                VALUES (%s, %s, %s, %s, %s)
                RETURNING id
            """, (
                phone,
                username,
                generate_password_hash(password),
                own_code,
                referred_by
            ))

            db.commit()
            user_id = cursor.fetchone()["id"]

        except psycopg.IntegrityError:
            db.rollback()
            flash(
                "That username, phone number or referral code "
                "could not be registered. Please try again.",
                "error"
            )
            return redirect(url_for("register"))

        session.clear()
        session["user_id"] = user_id
        session["_csrf_token"] = secrets.token_urlsafe(32)

        flash("Welcome to Alixo Earn! Your account has been created.", "success")
        return redirect(url_for("dashboard"))

    referral_code = request.args.get("referral_code", "").strip().upper()
    return render_template("register.html", referral_code=referral_code)


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        if not valid_csrf():
            flash("Your form expired. Please try again.", "error")
            return redirect(url_for("login"))

        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        user = get_db().execute(
            "SELECT * FROM users WHERE LOWER(username) = LOWER(%s)",
            (username,)
        ).fetchone()

        if not user or not check_password_hash(
            user["password_hash"], password
        ):
            flash("Incorrect username or password.", "error")
            return redirect(url_for("login"))

        session.clear()
        session["user_id"] = user["id"]
        session["_csrf_token"] = secrets.token_urlsafe(32)

        flash("You are now logged in.", "success")
        return redirect(url_for("dashboard"))

    return render_template("login.html")


